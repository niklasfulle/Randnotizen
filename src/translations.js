const messages = Object.fromEntries(['de', 'en'].map((language, languageIndex) => [
  language,
  Object.fromEntries(Object.entries(messagePairs).map(([key, values]) => [key, values[languageIndex]])),
]));

function normalizeLanguage(language) {
  return language === 'en' ? 'en' : 'de';
}

function normalizeTheme(theme) {
  return theme === 'dark' ? 'dark' : 'light';
}

function normalizeDesign(design) {
  const designs = ['paper', 'dark', 'blueprint', 'sunset', 'pastel', 'newspaper', 'neon', 'minimal'];
  return designs.includes(design) ? design : 'paper';
}

function themeForDesign(design) {
  return ['dark', 'blueprint', 'neon'].includes(normalizeDesign(design)) ? 'dark' : 'light';
}

function normalizeFont(font) {
  const legacyFonts = {
    segoe: 'inter',
    arial: 'inter',
    verdana: 'atkinson',
    georgia: 'lora',
    courier: 'jetbrains-mono',
  };
  const bundledFonts = ['inter', 'nunito-sans', 'atkinson', 'lora', 'jetbrains-mono', 'scoutie-sans', 'betania-patmos', 'playfair-display', 'ubuntu', 'space-grotesk', 'ibm-plex-mono'];
  return legacyFonts[font] || (bundledFonts.includes(font) ? font : 'inter');
}

function translate(language, key, variables = {}) {
  const normalized = normalizeLanguage(language);
  const template = messages[normalized][key] ?? messages.de[key] ?? key;
  return template.replaceAll(/\{(\w+)\}/g, (_match, name) => String(variables[name] ?? `{${name}}`));
}

const translations = {
  messages,
  normalizeLanguage,
  normalizeTheme,
  normalizeDesign,
  themeForDesign,
  normalizeFont,
  translate,
};

if (typeof module !== 'undefined' && module.exports) module.exports = translations;
globalObject.RandnotizenI18n = translations;
